def _rot(r, p, y):
    cr, sr, cp, sp, cy, sy = np.cos(r / 2), np.sin(r / 2), np.cos(p / 2), np.sin(p / 2), np.cos(y / 2), np.sin(y / 2)
    w = cr * cp * cy + sr * sp * sy
    x = sr * cp * cy - cr * sp * sy
    yy = cr * sp * cy + sr * cp * sy
    z = cr * cp * sy - sr * sp * cy
    n = np.sqrt(x * x + yy * yy + z * z)
    if n < 1e-9:
        return np.zeros(3), np.eye(3)
    v = np.array([x, yy, z]) / n * 2 * np.arctan2(n, w)
    R = np.array([[1 - 2 * (yy * yy + z * z), 2 * (x * yy - w * z), 2 * (x * z + w * yy)],
                  [2 * (x * yy + w * z), 1 - 2 * (x * x + z * z), 2 * (yy * z - w * x)],
                  [2 * (x * z - w * yy), 2 * (yy * z + w * x), 1 - 2 * (x * x + yy * yy)]])
    return v, R


def controller(obs: dict) -> np.ndarray:
    rv, R = _rot(obs["roll"], obs["pitch"], obs["yaw"])
    e = np.concatenate([np.zeros(3), rv, obs["joint_angles"][PERM] - Q_EQ[7:], obs["root_velocity"],
                        R.T @ obs["root_angular_velocity"], obs["joint_rates"][PERM]])
    return np.clip(U_EQ - GAIN * (K @ e), -0.4, 0.4)
