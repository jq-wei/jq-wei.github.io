TAIL_SLOPE = 0.07


def _cheb(i, u):
    """Clenshaw evaluation of the Chebyshev series of step i[j] at u[j]."""
    c = COEF[i]
    b1 = np.zeros_like(u)
    b2 = np.zeros_like(u)
    for k in range(c.shape[1] - 1, 0, -1):
        b1, b2 = c[:, k] + 2.0 * u * b1 - b2, b1
    return c[:, 0] + u * b1 - b2


def controller(obs: dict) -> np.ndarray:
    x0 = np.asarray(obs["x0"], dtype=float)
    flat = x0.reshape(-1)
    ax = np.abs(flat)
    axc = np.minimum(ax, XEND)
    i = np.searchsorted(T, axc, side="right")
    u = (axc - C[i]) / W[i]
    val = _cheb(i, u) + TAIL_SLOPE * (ax - axc)
    x1 = np.sign(flat) * val
    x1 = flat + np.clip(x1 - flat, -1000.0, 1000.0)
    return x1.reshape(x0.shape)
